function quoted(msg: string) {
  return [...msg.matchAll(/'([^']*)'/g)].map(m => m[1]);
}

export function explain(d: Diag): string {
  const t = C[d.id];
  if (!t) return '';
  const a = d.args?.length ? d.args : quoted(d.msg);
  return t.replace(/\{(\d)\}/g, (_, i) => esc(a[+i] ?? ''));
}

export function explainRuntime(type: string): string {
  return R[type] ?? 'Программа упала во время работы.';
}

function esc(s: string) {
  return s.replace(/[&<>]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]!));
}
